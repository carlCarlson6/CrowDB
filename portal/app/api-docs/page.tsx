"use client";

import Link from "next/link";
import { useCallback, useEffect, useState } from "react";

// The API docs section renders the server's own OpenAPI document (docs/006):
// the server generates it from its mapped routes, so this page always shows
// the running server, not a copy that could drift. Fetched through the same
// same-origin /api proxy route as the console — no API URL in client code.
const API = "/api";

/** The parts of the OpenAPI document this page reads. */
type SecurityScheme = {
  type?: string;
  in?: string;
  name?: string;
};

type Parameter = { name: string; in?: string; required?: boolean };

type Operation = {
  summary?: string;
  description?: string;
  parameters?: Parameter[];
  requestBody?: { required?: boolean; content?: Record<string, unknown> };
  responses?: Record<string, { description?: string }>;
};

type OpenApiDocument = {
  openapi?: string;
  info?: { title?: string; version?: string };
  paths?: Record<string, Record<string, Operation>>;
  components?: { securitySchemes?: Record<string, SecurityScheme> };
  security?: unknown[];
};

/** Reads the document into one flat, ordered operation list. */
function flatten(
  document: OpenApiDocument,
): Array<{ method: string; path: string; operation: Operation }> {
  const operations: Array<{ method: string; path: string; operation: Operation }> = [];
  for (const [path, methods] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(methods ?? {})) {
      operations.push({ method, path, operation });
    }
  }
  return operations.sort(
    (left, right) =>
      left.path.localeCompare(right.path) || methodOrder(left.method) - methodOrder(right.method),
  );
}

/** Read, then write, then delete — the order the operations come in. */
const METHOD_ORDER = ["get", "post", "put", "patch", "delete"];

function methodOrder(method: string): number {
  const index = METHOD_ORDER.indexOf(method);
  return index === -1 ? METHOD_ORDER.length : index;
}

export default function ApiDocs() {
  const [document, setDocument] = useState<OpenApiDocument | null>(null);
  const [offline, setOffline] = useState<string | null>(null);

  const load = useCallback(async () => {
    try {
      const res = await fetch(`${API}/openapi/v1.json`, { cache: "no-store" });
      if (!res.ok) throw new Error(await describe(res));
      setDocument((await res.json()) as OpenApiDocument);
      setOffline(null);
    } catch (error) {
      setDocument(null);
      setOffline(message(error));
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  const operations = document === null ? [] : flatten(document);

  return (
    <main className="console">
      <header className="topbar">
        <h1>
          CrowDB <span className="muted">API docs</span>
        </h1>
        <nav className="nav">
          <Link href="/">Console</Link>
          <Link href="/api-docs" className="active" aria-current="page">
            API docs
          </Link>
        </nav>
        <span className={offline !== null ? "pill bad" : "pill good"}>
          {offline !== null
            ? "API offline"
            : document === null
              ? "loading…"
              : `connected — ${operations.length} operations`}
        </span>
      </header>

      {offline !== null && (
        <p className="banner bad">
          Cannot reach the API: {offline} — is the server running?{" "}
          <code>dotnet run --project src/CrowDB.Server</code>{" "}
          <button onClick={() => void load()}>Retry</button>
        </p>
      )}

      {document === null && offline === null && (
        <p className="muted">Fetching the OpenAPI document…</p>
      )}

      {document !== null && (
        <section className="panel docs">
          <p className="docs-meta">
            {document.info?.title ?? "CrowDB API"} · OpenAPI {document.openapi ?? "?"} ·{" "}
            <a href={`${API}/openapi/v1.json`} target="_blank" rel="noreferrer">
              raw JSON
            </a>{" "}
            · generated by the server from its routes
          </p>

          <SecurityNotice document={document} />

          {operations.map(({ method, path, operation }) => (
            <article className="operation" key={`${method} ${path}`}>
              <div className="op-head">
                <span className={`method ${method}`}>{method}</span>
                <code>{path}</code>
              </div>
              {operation.summary && <p className="op-summary">{operation.summary}</p>}
              {operation.description && <p className="op-desc">{operation.description}</p>}
              {operation.parameters && operation.parameters.length > 0 && (
                <p className="detail">
                  parameters:{" "}
                  {operation.parameters
                    .map((parameter) =>
                      parameter.in ? `${parameter.name} (${parameter.in})` : parameter.name,
                    )
                    .join(", ")}
                </p>
              )}
              {operation.requestBody && (
                <p className="detail">
                  request body: {Object.keys(operation.requestBody.content ?? {}).join(", ") || "any"}{" "}
                  {operation.requestBody.required ? "(required)" : "(optional)"}
                </p>
              )}
              <ul className="responses">
                {Object.entries(operation.responses ?? {}).map(([code, response]) => (
                  <li key={code}>
                    <code>{code}</code>
                    <span>{response.description ?? ""}</span>
                  </li>
                ))}
              </ul>
            </article>
          ))}
        </section>
      )}
    </main>
  );
}

/**
 * The document always carries a security section (docs/007: every server has
 * a key), so this note describes that gate rather than appearing conditionally.
 */
function SecurityNotice({ document }: { document: OpenApiDocument }) {
  const schemes = Object.entries(document.components?.securitySchemes ?? {});
  if (schemes.length === 0 || !document.security?.length) return null;

  return (
    <p className="banner">
      This server requires authentication on every data request:{" "}
      {schemes
        .map(([id, scheme]) =>
          scheme.name ? `${scheme.name} (${scheme.type ?? id}, ${scheme.in ?? "header"})` : id,
        )
        .join(", ")}
      . The API docs themselves stay public.
    </p>
  );
}

function message(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

async function describe(res: Response): Promise<string> {
  const text = (await res.text()).trim();
  const detail = text.length > 0 ? ` — ${text.slice(0, 300)}` : "";
  return `HTTP ${res.status} ${res.statusText}${detail}`;
}
